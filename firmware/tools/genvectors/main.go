// Command genvectors turns tests/vectors/lora_v4.json into a Go table for
// the on-board self-test (cmd/selftest), which has no JSON parser:
//
//	go run ./tools/genvectors ../tests/vectors/lora_v4.json > cmd/selftest/vectors_gen.go
package main

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genvectors lora_v4.json")
		os.Exit(2)
	}
	out, err := generate(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.WriteString(out)
}

// generate returns the Go source of the table.
func generate(path string) (string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var v struct {
		Version    string                       `json:"version"`
		NetworkKey string                       `json:"network_key"`
		AppKeys    map[string]map[string]string `json:"app_keys"`
		Frames     []struct {
			Name, Plain, Below, Wire string
			Fcnt                     uint32
		} `json:"frames"`
		AppReplay struct{ Wire string } `json:"app_replay"`
	}
	if err := json.Unmarshal(raw, &v); err != nil {
		return "", err
	}
	var bad error
	bytesOf := func(h string) string {
		b, err := hex.DecodeString(h)
		if err != nil {
			bad = err
		}
		parts := make([]string, len(b))
		for i, x := range b {
			parts[i] = fmt.Sprintf("0x%02x", x)
		}
		return "[]byte{" + strings.Join(parts, ", ") + "}"
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by tools/genvectors from tests/vectors/lora_v4.json; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "package main\n\n")
	fmt.Fprintf(&out, "const vectorVersion = %q\n\n", v.Version)
	fmt.Fprintf(&out, "var networkKey = [16]byte(%s)\n\n", bytesOf(v.NetworkKey))
	fmt.Fprintf(&out, "var appKey = [16]byte(%s)\n\n", bytesOf(v.AppKeys["0x01"]["0"]))
	fmt.Fprintf(&out, "var appReplay = %s\n\n", bytesOf(v.AppReplay.Wire))
	fmt.Fprintf(&out, "var wireVectors = []wireVector{\n")
	for _, f := range v.Frames {
		fmt.Fprintf(&out, "\t{%q, %s, %s, %s, %d},\n", f.Name, bytesOf(f.Plain), bytesOf(f.Below), bytesOf(f.Wire), f.Fcnt)
	}
	fmt.Fprintf(&out, "}\n")
	return out.String(), bad
}
